CREATE OR REPLACE TABLE RECON.TXN_FEATURES AS
WITH BURST AS (
    SELECT a.TXN_ID, COUNT(*) AS CNT_10M
    FROM RECON.LEDGER a
    JOIN RECON.LEDGER b
      ON a.CUSTOMER_ID = b.CUSTOMER_ID
     AND b.TXN_TS BETWEEN ADD_MINUTES(a.TXN_TS, -10) AND a.TXN_TS
    GROUP BY a.TXN_ID
),
CUST AS (
    SELECT CUSTOMER_ID, SUM(AMOUNT) AS SUM_AMT, COUNT(*) AS N_TXN
    FROM RECON.LEDGER
    GROUP BY CUSTOMER_ID
),
DEV AS (
    SELECT CUSTOMER_ID, DEVICE_ID, COUNT(*) AS DEV_CNT
    FROM RECON.LEDGER
    GROUP BY CUSTOMER_ID, DEVICE_ID
),
CITY_CNT AS (
    SELECT CUSTOMER_ID, CITY, COUNT(*) AS C
    FROM RECON.LEDGER
    GROUP BY CUSTOMER_ID, CITY
),
HOME AS (
    SELECT CUSTOMER_ID, CITY AS HOME_CITY
    FROM (
        SELECT CUSTOMER_ID, CITY,
               ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY C DESC, CITY) AS RK
        FROM CITY_CNT
    ) t
    WHERE RK = 1
)
SELECT l.TXN_ID,
       l.CUSTOMER_ID,
       l.ACCOUNT_ID,
       l.AMOUNT,
       l.CITY,
       l.TXN_TS,
       bu.CNT_10M,
       CASE WHEN c.N_TXN > 1
            THEN l.AMOUNT / NULLIF((c.SUM_AMT - l.AMOUNT) / (c.N_TXN - 1), 0)
            ELSE 1 END AS AMT_RATIO,
       d.DEV_CNT * 1.0 / c.N_TXN AS DEV_SHARE,
       CASE WHEN l.CITY <> h.HOME_CITY THEN 1 ELSE 0 END AS OFF_HOME,
       CASE WHEN cd.COUNTRY <> 'India' THEN 1 ELSE 0 END AS IS_FOREIGN,
       CASE WHEN EXTRACT(HOUR FROM l.TXN_TS) < 5 THEN 1 ELSE 0 END AS IS_NIGHT
FROM RECON.LEDGER l
JOIN BURST bu ON bu.TXN_ID = l.TXN_ID
JOIN CUST c ON c.CUSTOMER_ID = l.CUSTOMER_ID
JOIN DEV d ON d.CUSTOMER_ID = l.CUSTOMER_ID AND d.DEVICE_ID = l.DEVICE_ID
JOIN HOME h ON h.CUSTOMER_ID = l.CUSTOMER_ID
JOIN RECON.CITY_DIM cd ON cd.CITY = l.CITY;

CREATE OR REPLACE TABLE RECON.FRAUD_SCORES AS
SELECT TXN_ID, CUSTOMER_ID, ACCOUNT_ID, AMOUNT, CITY, TXN_TS,
       SCORE,
       CASE WHEN SCORE >= 60 THEN 'HIGH' WHEN SCORE >= 35 THEN 'MEDIUM' ELSE 'LOW' END AS RISK_BAND,
       REASONS
FROM (
    SELECT f.*,
           LEAST(100,
               CASE WHEN CNT_10M >= 5 THEN 45 WHEN CNT_10M >= 3 THEN 20 ELSE 0 END
             + CASE WHEN AMT_RATIO >= 15 THEN 50 WHEN AMT_RATIO >= 6 THEN 20 ELSE 0 END
             + CASE WHEN IS_FOREIGN = 1 THEN 35 WHEN OFF_HOME = 1 THEN 8 ELSE 0 END
             + CASE WHEN DEV_SHARE < 0.35 THEN 15 ELSE 0 END
             + CASE WHEN IS_FOREIGN = 1 AND DEV_SHARE < 0.35 THEN 15 ELSE 0 END
             + CASE WHEN IS_NIGHT = 1 AND AMT_RATIO >= 3 THEN 10 ELSE 0 END
           ) AS SCORE,
           (CASE WHEN CNT_10M >= 3 THEN 'velocity burst, ' ELSE '' END
         || CASE WHEN AMT_RATIO >= 6 THEN 'amount far above customer norm, ' ELSE '' END
         || CASE WHEN IS_FOREIGN = 1 THEN 'foreign location, ' WHEN OFF_HOME = 1 THEN 'away from home city, ' ELSE '' END
         || CASE WHEN DEV_SHARE < 0.35 THEN 'rarely used device, ' ELSE '' END
         || CASE WHEN IS_NIGHT = 1 AND AMT_RATIO >= 3 THEN 'night-time high value, ' ELSE '' END) AS REASONS
    FROM RECON.TXN_FEATURES f
) s;

CREATE OR REPLACE VIEW RECON.FRAUD_METRICS AS
SELECT TRUE_POS,
       FALSE_POS,
       FALSE_NEG,
       ROUND(TRUE_POS * 100.0 / NULLIF(TRUE_POS + FALSE_POS, 0), 1) AS PRECISION_PCT,
       ROUND(TRUE_POS * 100.0 / NULLIF(TRUE_POS + FALSE_NEG, 0), 1) AS RECALL_PCT
FROM (
    SELECT SUM(CASE WHEN s.RISK_BAND = 'HIGH' AND t.IS_FRAUD = 1 THEN 1 ELSE 0 END) AS TRUE_POS,
           SUM(CASE WHEN s.RISK_BAND = 'HIGH' AND t.IS_FRAUD = 0 THEN 1 ELSE 0 END) AS FALSE_POS,
           SUM(CASE WHEN s.RISK_BAND <> 'HIGH' AND t.IS_FRAUD = 1 THEN 1 ELSE 0 END) AS FALSE_NEG
    FROM RECON.FRAUD_SCORES s
    JOIN RECON.FRAUD_TRUTH t ON t.TXN_ID = s.TXN_ID
) m;