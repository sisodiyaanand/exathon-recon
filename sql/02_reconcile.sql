CREATE OR REPLACE TABLE RECON.BANK_RANKED AS
SELECT BANK_REF, TXN_REF, ACCOUNT_ID, AMOUNT, VALUE_DATE,
       ROW_NUMBER() OVER (PARTITION BY COALESCE(TXN_REF, BANK_REF) ORDER BY BANK_REF) AS RK
FROM RECON.BANK_STATEMENT;

CREATE OR REPLACE TABLE RECON.MATCH_REF AS
SELECT l.TXN_ID,
       b.BANK_REF,
       CASE WHEN l.AMOUNT = b.AMOUNT THEN 'MATCHED' ELSE 'AMOUNT_MISMATCH' END AS STATUS,
       b.AMOUNT - l.AMOUNT AS VARIANCE_AMT,
       'REFERENCE' AS MATCH_TYPE
FROM RECON.LEDGER l
JOIN RECON.BANK_RANKED b ON l.TXN_REF = b.TXN_REF AND b.RK = 1;

CREATE OR REPLACE TABLE RECON.MATCH_FUZZY AS
SELECT TXN_ID,
       BANK_REF,
       'MATCHED_FUZZY' AS STATUS,
       CAST(0 AS DECIMAL(14,2)) AS VARIANCE_AMT,
       'ACCOUNT+AMOUNT+DATE' AS MATCH_TYPE
FROM (
    SELECT l.TXN_ID,
           b.BANK_REF,
           ROW_NUMBER() OVER (PARTITION BY l.TXN_ID ORDER BY b.VALUE_DATE, b.BANK_REF) AS RK_L,
           ROW_NUMBER() OVER (PARTITION BY b.BANK_REF ORDER BY l.TXN_ID) AS RK_B
    FROM RECON.LEDGER l
    JOIN RECON.BANK_STATEMENT b
      ON b.TXN_REF IS NULL
     AND l.ACCOUNT_ID = b.ACCOUNT_ID
     AND l.AMOUNT = b.AMOUNT
     AND b.VALUE_DATE BETWEEN CAST(l.TXN_TS AS DATE) AND ADD_DAYS(CAST(l.TXN_TS AS DATE), 2)
    WHERE l.TXN_ID NOT IN (SELECT TXN_ID FROM RECON.MATCH_REF)
) t
WHERE RK_L = 1 AND RK_B = 1;

CREATE OR REPLACE TABLE RECON.RECON_RESULT AS
SELECT TXN_ID, BANK_REF, STATUS, VARIANCE_AMT, MATCH_TYPE FROM RECON.MATCH_REF
UNION ALL
SELECT TXN_ID, BANK_REF, STATUS, VARIANCE_AMT, MATCH_TYPE FROM RECON.MATCH_FUZZY
UNION ALL
SELECT l.TXN_ID, CAST(NULL AS VARCHAR(20)), 'MISSING_IN_BANK', l.AMOUNT, 'NONE'
FROM RECON.LEDGER l
WHERE l.TXN_ID NOT IN (SELECT TXN_ID FROM RECON.MATCH_REF)
  AND l.TXN_ID NOT IN (SELECT TXN_ID FROM RECON.MATCH_FUZZY)
UNION ALL
SELECT l.TXN_ID, b.BANK_REF, 'DUPLICATE_POSTING', b.AMOUNT, 'REFERENCE'
FROM RECON.BANK_RANKED b
JOIN RECON.LEDGER l ON l.TXN_REF = b.TXN_REF
WHERE b.RK > 1
UNION ALL
SELECT CAST(NULL AS DECIMAL(12,0)), b.BANK_REF, 'UNMATCHED_BANK', b.AMOUNT, 'NONE'
FROM RECON.BANK_STATEMENT b
WHERE b.TXN_REF IS NULL
  AND b.BANK_REF NOT IN (SELECT BANK_REF FROM RECON.MATCH_FUZZY);

CREATE OR REPLACE VIEW RECON.RECON_SUMMARY AS
SELECT STATUS,
       COUNT(*) AS TXN_CNT,
       SUM(ABS(VARIANCE_AMT)) AS AMOUNT_IN_QUESTION
FROM RECON.RECON_RESULT
GROUP BY STATUS;